final class StubLogicTests: XCTestCase {
    let opts = StubOptions(thisMac: "op", deskPath: "/usr/local/bin/desk")
    func app(_ id: String, _ name: String, _ p: StubPolicy, icon: String? = nil) -> HostedApp {
        HostedApp(bundleId: id, name: name, version: "2.1", iconPath: icon, policy: p)
    }

    func testWhichAppsGetAStub() {
        XCTAssertFalse(StubGenerator.wantsStub(app("a", "A", .local), thisMac: "op"))
        XCTAssertTrue(StubGenerator.wantsStub(app("a", "A", .anywhere), thisMac: "op"))
        XCTAssertTrue(StubGenerator.wantsStub(app("a", "A", .home("big")), thisMac: "op"))
        // On the home Mac the real app is pinned instead (arrangement 2).
        XCTAssertFalse(StubGenerator.wantsStub(app("a", "A", .home("op")), thisMac: "op"))
    }

    func testBundleIdValidation() {
        for ok in ["org.mozilla.firefox", "com.hnc.Discord", "a-b_c.d1"] { XCTAssertTrue(StubGenerator.isSafeBundleId(ok), ok) }
        for bad in ["", "a b", "a;rm -rf /", "a$(x)", "a'b", "a\nb", "é.app", "-rf", "--x", String(repeating: "a", count: 156)] { XCTAssertFalse(StubGenerator.isSafeBundleId(bad), bad) }
    }

    func testDeskPathValidation() {
        XCTAssertTrue(StubGenerator.isSafeDeskPath("/usr/local/bin/desk"))
        for bad in ["desk", "/a\"b", "/a}b", "/a$b", "/a`b", "/a\\b", "/a\nb", ""] { XCTAssertFalse(StubGenerator.isSafeDeskPath(bad), bad) }
    }

    func testNameSanitizing() {
        XCTAssertEqual(StubGenerator.sanitizeName("Firefox"), "Firefox")
        XCTAssertEqual(StubGenerator.sanitizeName("A/B:C"), "A B C")
        XCTAssertEqual(StubGenerator.sanitizeName("..hidden"), "hidden")
        XCTAssertEqual(StubGenerator.sanitizeName("  x\ty  "), "x y")
        XCTAssertEqual(StubGenerator.sanitizeName("..."), "")
        XCTAssertLessThanOrEqual(StubGenerator.sanitizeName(String(repeating: "n", count: 300)).utf8.count, 100)
        XCTAssertEqual(StubGenerator.sanitizeName("Caf\u{00E9}"), "Caf\u{00E9}")
    }

    func testBundleContents() throws {
        let spec = try StubGenerator.make(app("org.mozilla.firefox", "Firefox", .home("big"), icon: "/Apps/Firefox.app/icon.icns"), options: opts).get()
        XCTAssertEqual(spec.dirName, "Firefox")
        XCTAssertEqual(spec.stubBundleId, "local.desk.stub.org.mozilla.firefox")
        XCTAssertEqual(spec.files.map { $0.path }, ["Contents/Info.plist", "Contents/MacOS/desk-stub", "Contents/Resources/AppIcon.icns"])
        XCTAssertEqual(spec.files.map { $0.executable }, [false, true, false])
        guard case .text(let plist) = spec.files[0].content, case .text(let script) = spec.files[1].content else { return XCTFail() }
        for needle in ["<key>CFBundleIdentifier</key>\n\t<string>local.desk.stub.org.mozilla.firefox</string>",
                       "<key>CFBundleName</key>\n\t<string>Firefox</string>",
                       "<key>CFBundleIconFile</key>\n\t<string>AppIcon.icns</string>",
                       "<key>DeskHostedBundleId</key>\n\t<string>org.mozilla.firefox</string>",
                       "<key>CFBundlePackageType</key>\n\t<string>APPL</string>",
                       "<key>DeskStubDigest</key>\n\t<string>\(spec.digest)</string>"] {
            XCTAssertTrue(plist.contains(needle), needle)
        }
        XCTAssertEqual(script, "#!/bin/sh\n# Generated by desk-stubgen. Edits are overwritten.\nexec \"/usr/local/bin/desk\" stub-run --bundle-id org.mozilla.firefox \"$@\"\n")
        XCTAssertEqual(spec.files[2].content, .copy(source: "/Apps/Firefox.app/icon.icns"))
    }

    func testNoIconMeansNoIconKeyOrFile() throws {
        let spec = try StubGenerator.make(app("x.y", "Y", .anywhere), options: opts).get()
        XCTAssertEqual(spec.files.count, 2)
        guard case .text(let plist) = spec.files[0].content else { return XCTFail() }
        XCTAssertFalse(plist.contains("CFBundleIconFile"))
    }

    func testPlistEscapesNames() throws {
        let spec = try StubGenerator.make(app("x.y", "Tom & <Jerry> \"Q\"", .anywhere), options: opts).get()
        guard case .text(let plist) = spec.files[0].content else { return XCTFail() }
        XCTAssertTrue(plist.contains("Tom &amp; &lt;Jerry&gt; &quot;Q&quot;"))
        XCTAssertFalse(plist.contains("<Jerry>"))
        XCTAssertEqual(StubGenerator.xmlEscape("a\u{1}b"), "ab")
    }

    func testRejections() {
        XCTAssertEqual(StubGenerator.make(app("bad id;", "X", .anywhere), options: opts), .failure(.badBundleId("bad id;")))
        XCTAssertEqual(StubGenerator.make(app("x.y", "...", .anywhere), options: opts), .failure(.emptyName("x.y")))
        XCTAssertEqual(StubGenerator.make(app("x.y", "X", .anywhere), options: StubOptions(thisMac: "op", deskPath: "/a\"b")), .failure(.badDeskPath("/a\"b")))
    }

    func testDigestChangesWithEveryInput() throws {
        let base = try StubGenerator.make(app("x.y", "Y", .anywhere), options: opts).get().digest
        var a = app("x.y", "Y", .anywhere); a.version = "3"
        XCTAssertNotEqual(try StubGenerator.make(a, options: opts).get().digest, base)
        XCTAssertNotEqual(try StubGenerator.make(app("x.y", "Y", .anywhere, icon: "/i.icns"), options: opts).get().digest, base)
        XCTAssertNotEqual(try StubGenerator.make(app("x.y", "Z", .anywhere), options: opts).get().digest, base)
        XCTAssertNotEqual(try StubGenerator.make(app("x.y", "Y", .anywhere), options: StubOptions(thisMac: "op", deskPath: "/opt/desk")).get().digest, base)
        XCTAssertEqual(try StubGenerator.make(app("x.y", "Y", .anywhere), options: opts).get().digest, base)
        XCTAssertEqual(base.count, 16)
    }
}

final class StubPlanTests: XCTestCase {
    let opts = StubOptions(thisMac: "op", deskPath: "/usr/local/bin/desk")
    let slack = HostedApp(bundleId: "com.tinyspeck.slackmacgap", name: "Slack", policy: .anywhere)
    let ff = HostedApp(bundleId: "org.mozilla.firefox", name: "Firefox", policy: .home("big"))
    let finder = HostedApp(bundleId: "com.apple.finder", name: "Finder", policy: .local)

    func testFreshMacGetsStubsForNonLocalApps() {
        let plan = StubPlanner.plan(apps: [slack, ff, finder], existing: [], options: opts)
        XCTAssertEqual(plan.actions.compactMap { if case .create(let s) = $0 { return s.dirName } else { return nil } }, ["Slack", "Firefox"]) // ordered by bundle id
        XCTAssertEqual(plan.actions.count, 2)
        XCTAssertTrue(plan.rejected.isEmpty)
    }

    func testSecondRunChangesNothing() throws {
        let first = StubPlanner.plan(apps: [slack, ff], existing: [], options: opts)
        let existing = first.actions.compactMap { a -> ExistingStub? in if case .create(let s) = a { return ExistingStub(dirName: s.dirName, hostedBundleId: s.hostedBundleId, digest: s.digest) } else { return nil } }
        XCTAssertEqual(existing.count, 2)
        XCTAssertEqual(StubPlanner.plan(apps: [slack, ff], existing: existing, options: opts).actions, [])
    }

    func testChangedAppIsReplacedAndStaleOneRemoved() {
        let first = StubPlanner.plan(apps: [slack, ff], existing: [], options: opts)
        var existing = first.actions.compactMap { a -> ExistingStub? in if case .create(let s) = a { return ExistingStub(dirName: s.dirName, hostedBundleId: s.hostedBundleId, digest: s.digest) } else { return nil } }
        var slack2 = slack; slack2.version = "9.9"
        // Firefox becomes local to this Mac's home: no stub any more.
        var ff2 = ff; ff2.policy = .home("op")
        let plan = StubPlanner.plan(apps: [slack2, ff2], existing: existing, options: opts)
        XCTAssertEqual(plan.actions.count, 2)
        XCTAssertTrue(plan.actions.contains { if case .replace(let s, let old) = $0 { return s.hostedBundleId == slack.bundleId && old == nil } else { return false } })
        XCTAssertTrue(plan.actions.contains(.remove(dirName: "Firefox")))
        // A directory that is not ours is never touched.
        existing.append(ExistingStub(dirName: "Hand Made", hostedBundleId: nil, digest: nil))
        XCTAssertFalse(StubPlanner.plan(apps: [], existing: existing, options: opts).actions.contains(.remove(dirName: "Hand Made")))
    }

    func testRenamedAppReplacesUnderTheNewNameAndRemovesTheOld() {
        let old = ExistingStub(dirName: "Slack Old", hostedBundleId: slack.bundleId, digest: "x")
        let plan = StubPlanner.plan(apps: [slack], existing: [old], options: opts)
        guard case .replace(let s, let removing)? = plan.actions.first else { return XCTFail() }
        XCTAssertEqual(s.dirName, "Slack"); XCTAssertEqual(removing, "Slack Old")
    }

    func testNameClashGetsASuffixDeterministically() {
        let a = HostedApp(bundleId: "a.one", name: "Mail", policy: .anywhere)
        let b = HostedApp(bundleId: "b.two", name: "mail", policy: .anywhere)
        for order in [[a, b], [b, a]] {
            let names = StubPlanner.plan(apps: order, existing: [], options: opts).actions.compactMap { act -> String? in if case .create(let s) = act { return s.dirName } else { return nil } }
            XCTAssertEqual(names, ["Mail", "mail 2"])
        }
    }

    func testBadAppsAreRejectedNotWritten() {
        let bad = HostedApp(bundleId: "x;y", name: "X", policy: .anywhere)
        let plan = StubPlanner.plan(apps: [bad, slack], existing: [], options: opts)
        XCTAssertEqual(plan.rejected, [.badBundleId("x;y")])
        XCTAssertEqual(plan.actions, [], "one bad entry stops the whole run")
    }
}

